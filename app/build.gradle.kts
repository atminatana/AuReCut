// Release signing comes from the environment (GitHub Actions secrets); without it the release APK is unsigned.
val keystorePath: String? = System.getenv("KEYSTORE_PATH")

android {
    namespace = "org.aurecut.app"
    compileSdk = 35

    defaultConfig {
        applicationId = "org.aurecut.app"
        minSdk = 29
        targetSdk = 35
        // The release workflow passes both values derived from the git tag (v1.2.3 -> 1.2.3 / 10203).
        versionCode = (findProperty("appVersionCode") as String?)?.toInt() ?: 10000
        versionName = (findProperty("appVersionName") as String?) ?: "1.0.0"
    }

    signingConfigs {
        if (keystorePath != null) {
            create("release") {
                storeFile = file(keystorePath)
                storePassword = System.getenv("KEYSTORE_PASSWORD")
                keyAlias = System.getenv("KEY_ALIAS")
                keyPassword = System.getenv("KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (keystorePath != null) signingConfig = signingConfigs.getByName("release")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    buildFeatures {
        compose = true
    }

    packaging {
        resources.excludes += "/META-INF/{AL2.0,LGPL2.1}"
    }

    // Keeps the APK free of the encrypted dependency block (needed for F-Droid style reproducible builds).
    dependenciesInfo {
        includeInApk = false
        includeInBundle = false
    }

    lint {
        abortOnError = false
        checkReleaseBuilds = false
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

